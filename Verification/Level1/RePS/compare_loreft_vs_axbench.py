"""
Quantitative Comparison: Our LoReFTExtractor vs PyReFT
======================================================

Trains BOTH methods on the *same* refusal_cast_responses data, then compares
learned subspaces using:

  1. Principal angles between rotation subspaces (cos of canonical angles)
  2. Frobenius distance of projectors: ||R_ours R_ours^T - R_gt R_gt^T||_F
  3. Cosine similarity of learned source transforms (W matrices)
  4. Orthonormality sanity check: ||R R^T - I||_F ≈ 0

NO mock functions. Both methods are trained from random init on real data.

Usage (from repo root, sae_circuit env):
    conda run -n sae_circuit python Scripts/compare_loreft_vs_axbench.py \\
        [--layer 10] [--n-samples 100] [--epochs 3] [--rank 4] \\
        [--device cuda:0] [--seed 42] [--skip-our-run]
"""

