# ===========================================================================
# Subspace comparison utilities
# ===========================================================================

def principal_angles(R1: torch.Tensor, R2: torch.Tensor) -> torch.Tensor:
    """
    Principal angles between the row-spaces of R1 (r×d) and R2 (r×d).
    Both must have orthonormal rows (||r_i||=1, r_i·r_j=0).
    """
    M = R1.float() @ R2.float().T  # (r, r)
    sv = torch.linalg.svdvals(M).clamp(-1.0, 1.0)
    return sv.acos().sort().values


def projector_frobenius(R1: torch.Tensor, R2: torch.Tensor) -> tuple[float, float]:
    """
    ||P1 - P2||_F where Pi = R_i^T R_i (orthogonal projector onto rowspace).
    Returns (raw, normalised_by_sqrt_2r).
    """
    P1 = R1.float().T @ R1.float()  # (d, d)
    P2 = R2.float().T @ R2.float()
    raw = (P1 - P2).norm(p="fro").item()
    return raw, raw / (2 * R1.shape[0]) ** 0.5


def cos_sim_flat(A: torch.Tensor, B: torch.Tensor) -> float:
    a, b = A.float().flatten(), B.float().flatten()
    return F.cosine_similarity(a.unsqueeze(0), b.unsqueeze(0)).item()


def orthonormality_err(R: torch.Tensor) -> float:
    gram = R.float() @ R.float().T
    I = torch.eye(gram.shape[0])
    return (gram - I).norm(p="fro").item()


def subspace_principal_angles(W1: torch.Tensor, W2: torch.Tensor) -> torch.Tensor:
    """Principal angles between row-spaces of W1, W2 (after QR-orthogonalising)."""
    Q1, _ = torch.linalg.qr(W1.float().T)  # (d, r)
    Q2, _ = torch.linalg.qr(W2.float().T)
    return principal_angles(Q1.T, Q2.T)


